"""Generate board10.tcl (System Console, fed through stdin) for the EXP-S19 full on-chip psv run.
Usage: python gen_board10.py <csr10.json> <run10.json> <out tcl>
Tcl usage: set argv [list <run dir (prog10 output)> <setup dir (hw8)> <readback 0/1>]; source board10.tcl"""
import json, sys
C = json.load(open(sys.argv[1]))
R = json.load(open(sys.argv[2]))
A = R['ddr']
o = lambda c, a: hex(C[c]['base'] + C[c]['args'][a])
t = f'''# EXP-S19: full on-chip list-mode psv run (generated by gen_board10.py)
set rd [lindex $argv 0]; set hs [lindex $argv 1]; set RB [lindex $argv 2]
set SRC 0x0; set SNK 0x10000; set SIO 0x40000; set SROW 0x180000; set DIO 0x200000; set DMA 0x210000; set VOX 0x220000
set SEQ 0x250000; set SPROG 0x260000; set SLOG 0x280000
set C_START 0x08; set C_STATUS 0x18; set DONE 0x2
set m [lindex [get_service_paths master] 0]
open_service master $m
puts "master: $m"
proc rd32 {{a}} {{ global m; return [master_read_32 $m $a 1] }}
proc wr32 {{a v}} {{ global m; master_write_32 $m $a $v }}
proc wr64 {{a v}} {{ wr32 $a [expr {{$v & 0xffffffff}}]; wr32 [expr {{$a + 4}}] [expr {{$v >> 32}}] }}
proc waitdone {{base what}} {{
  global C_STATUS DONE
  set t0 [clock milliseconds]
  while {{([rd32 [expr {{$base + $C_STATUS}}]] & $DONE) == 0}} {{ if {{[clock milliseconds] - $t0 > 900000}} {{ puts "TIMEOUT $what"; exit 1 }} }}
  wr32 [expr {{$base + $C_STATUS}}] $DONE
}}
proc f2u {{x}} {{ binary scan [binary format f $x] i u; return [expr {{$u & 0xffffffff}}] }}
proc go {{mode nev off cnt nm}} {{
  global SRC SNK C_START
  wr32 {o('sink', 'nm')} $nm; wr32 {o('sink', 'nq')} 0; wr32 {o('sink', 'raw')} 0
  wr32 [expr {{$SNK + $C_START}}] 1
  wr32 {o('src', 'mode')} $mode; wr32 {o('src', 'nev')} $nev; wr32 {o('src', 'off')} $off; wr32 {o('src', 'cnt')} $cnt
  wr32 {o('src', 'rep')} 1; wr32 {o('src', 'finit')} 0
  wr32 [expr {{$SRC + $C_START}}] 1
  waitdone $SNK sink; waitdone $SRC src
}}
proc dma {{dir ch addr file n}} {{
  global m DIO DMA C_START rd
  set wbase [expr {{$addr / 64}}]
  if {{$dir == 0}} {{ set fi [open $file rb]; fconfigure $fi -translation binary; set n [expr {{[file size $file] / 64}}] }} else {{ set fo [open $file wb]; fconfigure $fo -translation binary }}
  for {{set off 0}} {{$off < $n}} {{incr off 1024}} {{
    set c [expr {{min(1024, $n - $off)}}]
    if {{$dir == 0}} {{
      set f [open [file join $rd chunk.bin] wb]; fconfigure $f -translation binary
      puts -nonewline $f [read $fi [expr {{64 * $c}}]]; close $f
      master_write_from_file $m [file join $rd chunk.bin] $DIO
    }}
    foreach {{a v}} [list {o('dma', 'm1')} 0 {o('dma', 'm2')} 0 {o('dma', 'm3')} 0 {o('dma', 'm4')} 0] {{ wr64 $a $v }}
    wr32 {o('dma', 'ch')} $ch; wr32 {o('dma', 'dir')} $dir; wr32 {o('dma', 'base')} [expr {{$wbase + $off}}]; wr32 {o('dma', 'n')} $c
    wr32 [expr {{$DMA + $C_START}}] 1
    waitdone $DMA dma
    if {{$dir == 1}} {{
      master_read_to_file $m [file join $rd chunk.bin] $DIO [expr {{64 * $c}}]
      set f [open [file join $rd chunk.bin] rb]; fconfigure $f -translation binary
      puts -nonewline $fo [read $f]; close $f
    }}
  }}
  if {{$dir == 0}} {{ close $fi }} else {{ close $fo }}
}}
# ---- 1) lane ids, plane tables, TOF table
master_write_from_file $m [file join $hs rowt.bin] $SROW
go 4 0 0 0 1
master_write_from_file $m [file join $hs setup_io.bin] $SIO
set NSETUP [expr {{[file size [file join $hs setup_io.bin]] / 28}}]
go 7 0 0 $NSETUP $NSETUP
set fi [open [file join $hs toftab_io.bin] rb]; fconfigure $fi -translation binary
for {{set off 0}} {{$off < 1024}} {{incr off 512}} {{
  set f [open [file join $rd chunk.bin] wb]; fconfigure $f -translation binary
  puts -nonewline $f [read $fi [expr {{8 * 512}}]]; close $f
  master_write_from_file $m [file join $rd chunk.bin] $SIO
  go 9 0 $off 512 512
}}
close $fi
puts "lane tables loaded"
# ---- 2) DDR images
set t0 [clock milliseconds]
set fd [open [file join $rd ddr.txt]]; set lines [split [string trim [read $fd]] "\\n"]; close $fd
foreach ln $lines {{ lassign $ln fn ch ad; dma 0 $ch $ad [file join $rd $fn] 0 }}
puts "DDR loaded in [expr {{[clock milliseconds] - $t0}}] ms"
# ---- 3) lanes <- x0 (voxel unit mode 4: lane = P0 > 0 ? x0 : 0)
foreach {{a v}} [list {o('vox', 'mx')} {A['X'][1]} {o('vox', 'mxn')} {A['X'][1]} {o('vox', 'mp')} {A['P'][1]} {o('vox', 'mt')} {A['T'][1]} {o('vox', 'mtw')} {A['T'][1]} {o('vox', 'mg')} {A['GS'][1]} {o('vox', 'mgw')} {A['GS'][1]} {o('vox', 'mgp')} {A['GP'][1]} {o('vox', 'mxr')} {A['XS'][1]}] {{ wr64 $a $v }}
wr32 {o('vox', 'mode')} 4; wr32 {o('vox', 'nd')} 47000; wr32 {o('vox', 'rep')} 1
wr32 {o('vox', 'step')} [f2u 0.0]; wr32 {o('vox', 'mf')} [f2u 8.0]; wr32 {o('vox', 'invm')} [f2u 0.125]
wr32 {o('sink', 'nm')} 4; wr32 {o('sink', 'nq')} 0; wr32 {o('sink', 'raw')} 0; wr32 [expr {{$SNK + $C_START}}] 1
wr32 [expr {{$VOX + $C_START}}] 1
wr32 {o('src', 'mode')} 11; wr32 {o('src', 'rep')} 1; wr32 [expr {{$SRC + $C_START}}] 1
waitdone $VOX vox; waitdone $SNK sink; waitdone $SRC src
puts "lanes loaded (x0)"
# ---- 4) sequencer program, then the timed run
master_write_from_file $m [file join $rd prog.bin] $SPROG
wr64 {o('seq', 'csr')} 0
wr32 {o('seq', 'start0')} 0
set t0 [clock microseconds]
wr32 [expr {{$SEQ + $C_START}}] 1
while {{([rd32 [expr {{$SEQ + $C_STATUS}}]] & $DONE) == 0}} {{ }}
set us [expr {{[clock microseconds] - $t0}}]
wr32 [expr {{$SEQ + $C_STATUS}}] $DONE
puts "RUN {R['timed_updates']} timed updates: $us us (host timer, JTAG poll granularity)"
wr32 {o('seq', 'start0')} {R['prog_split']}
wr32 [expr {{$SEQ + $C_START}}] 1
waitdone $SEQ seq2
puts "updates 40..49 done (untimed)"
master_read_to_file $m [file join $rd board_slog.bin] $SLOG 1024
# ---- 5) read back x_1 .. x_40 (slot order) and the last raster
if {{$RB}} {{
  for {{set u 1}} {{$u <= 50}} {{incr u}} {{ dma 1 1 [expr {{{A['X'][1]} + $u * 0x800000}}] [file join $rd board_x$u.bin] 117500 }}
  puts "x archive read back"
}}
close_service master $m
'''
open(sys.argv[3], 'w').write(t)
print('ok')
